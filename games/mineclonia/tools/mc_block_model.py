#!/usr/bin/env python3
"""Converts a Minecraft block model (assets/minecraft/models/block/*.json,
with its parents) into a Wavefront OBJ for a Luanti "mesh" node.

One OBJ material per texture variable, in the order of first use; they are
the node's tiles in that order (printed on stdout).

Coordinates: Minecraft model units are 1/16 of a block from the block's
corner; Luanti node meshes are in nodes around the node center, and
Luanti's +Z is Minecraft's north (-Z). Irrlicht's OBJ loader mirrors X when
loading (right- to left-handed), so X is written mirrored.

Usage: mc_block_model.py MODEL_DIR MODEL_NAME OUT.obj
"""

import json
import math
import os
import sys


def load_model(model_dir, name):
    name = name.split(":")[-1]
    if name.startswith("block/"):
        name = name[len("block/"):]
    with open(os.path.join(model_dir, name + ".json")) as f:
        m = json.load(f)
    textures = {}
    elements = None
    parent = m.get("parent")
    if parent and parent.split(":")[-1] not in ("block/block",):
        p_tex, p_el = load_model(model_dir, parent)
        textures.update(p_tex)
        elements = p_el
    textures.update(m.get("textures", {}))
    if "elements" in m:
        elements = m["elements"]
    return textures, elements


def rotate(v, rot):
    if not rot:
        return v
    angle = math.radians(rot["angle"])
    ox, oy, oz = rot["origin"]
    x, y, z = v[0] - ox, v[1] - oy, v[2] - oz
    c, s = math.cos(angle), math.sin(angle)
    axis = rot["axis"]
    rescale = 1 / math.cos(angle) if rot.get("rescale") else 1
    # BlockMath / FaceBakery.applyElementRotation: rotation about the axis,
    # rescaling the two other axes
    if axis == "y":
        x, z = x * c + z * s, -x * s + z * c
        x, z = x * rescale, z * rescale
    elif axis == "x":
        y, z = y * c - z * s, y * s + z * c
        y, z = y * rescale, z * rescale
    elif axis == "z":
        x, y = x * c - y * s, x * s + y * c
        x, y = x * rescale, y * rescale
    return (x + ox, y + oy, z + oz)


NORMALS = {
    "north": (0, 0, -1), "south": (0, 0, 1), "west": (-1, 0, 0),
    "east": (1, 0, 0), "up": (0, 1, 0), "down": (0, -1, 0),
}


def face_corners(face, f, t):
    """Corners (top-left, top-right, bottom-right, bottom-left) of a face as
    seen from outside the element, Minecraft coordinates."""
    x1, y1, z1 = f
    x2, y2, z2 = t
    if face == "north":
        return [(x2, y2, z1), (x1, y2, z1), (x1, y1, z1), (x2, y1, z1)]
    if face == "south":
        return [(x1, y2, z2), (x2, y2, z2), (x2, y1, z2), (x1, y1, z2)]
    if face == "east":
        return [(x2, y2, z2), (x2, y2, z1), (x2, y1, z1), (x2, y1, z2)]
    if face == "west":
        return [(x1, y2, z1), (x1, y2, z2), (x1, y1, z2), (x1, y1, z1)]
    if face == "up":
        return [(x1, y2, z1), (x2, y2, z1), (x2, y2, z2), (x1, y2, z2)]
    if face == "down":
        return [(x1, y1, z2), (x2, y1, z2), (x2, y1, z1), (x1, y1, z1)]
    raise ValueError(face)


def rotate_dir(n, rot):
    """A face normal turned with the element (no rescale)."""
    if not rot:
        return n
    r = dict(rot, origin=[0, 0, 0], rescale=False)
    x, y, z = rotate(n, r)
    length = math.sqrt(x * x + y * y + z * z)
    return (x / length, y / length, z / length)


def to_luanti(v):
    x, y, z = v
    return (x / 16 - 0.5, y / 16 - 0.5, 0.5 - z / 16)


def convert(model_dir, name, out):
    textures, elements = load_model(model_dir, name)
    materials = []
    faces = {}
    for el in elements:
        f, t = el["from"], el["to"]
        rot = el.get("rotation")
        for face, fd in el["faces"].items():
            tex = fd["texture"].lstrip("#")
            if tex not in materials:
                materials.append(tex)
                faces[tex] = []
            uv = fd["uv"]
            u1, v1, u2, v2 = uv
            uvs = [(u1, v1), (u2, v1), (u2, v2), (u1, v2)]
            r = fd.get("rotation", 0)
            for _ in range(r // 90):
                uvs = uvs[-1:] + uvs[:-1]
            corners = [rotate(c, rot) for c in face_corners(face, f, t)]
            n = rotate_dir(NORMALS[face], rot)
            faces[tex].append((corners, uvs, n))
    lines = ["# Generated by tools/mc_block_model.py from Minecraft's %s" % name]
    vi = vt = vn = 0
    for i, tex in enumerate(materials):
        # The engine's OBJ loader makes one mesh buffer per group (it
        # ignores materials), in the order of the groups
        lines.append("g m%02d_%s" % (i, tex))
        for corners, uvs, n in faces[tex]:
            for c in corners:
                x, y, z = to_luanti(c)
                lines.append("v %.6f %.6f %.6f" % (-x, y, z))
            for u, v in uvs:
                lines.append("vt %.6f %.6f" % (u / 16, 1 - v / 16))
            nx, ny, nz = n
            lines.append("vn %.6f %.6f %.6f" % (-nx, ny, -nz))
            vn += 1
            # mirrored X flips the winding: list the corners reversed
            idx = [(vi + i + 1, vt + i + 1) for i in range(4)][::-1]
            lines.append("f " + " ".join("%d/%d/%d" % (a, b, vn) for a, b in idx))
            vi += 4
            vt += 4
    with open(out, "w") as fh:
        fh.write("\n".join(lines) + "\n")
    print("%s: tiles in order: %s" % (out, ", ".join(
        "%s=%s" % (m, textures.get(m, "?")) for m in materials)))


if __name__ == "__main__":
    convert(sys.argv[1], sys.argv[2], sys.argv[3])
