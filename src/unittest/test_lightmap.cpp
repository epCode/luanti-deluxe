class TestLightmap : public TestBase {
public:
	TestLightmap() { TestManager::registerTestModule(this); }
	const char *getName() override { return "TestLightmap"; }

	void runTests(IGameDef *gamedef) override;
	void testTexels();
};

static TestLightmap g_test_instance;

void TestLightmap::runTests(IGameDef *gamedef)
{
	TEST(testTexels);
}

static void check_table(const LightmapState &state, const u8 (&expected)[16][16][3])
{
	for (int sky = 0; sky < 16; sky++)
	for (int block = 0; block < 16; block++) {
		video::SColorf c = state.texel(block, sky);
		const u8 *e = expected[sky][block];
		const f32 got[3] = {c.r * 255.0f, c.g * 255.0f, c.b * 255.0f};
		for (int i = 0; i < 3; i++)
			UASSERT(std::fabs(got[i] - e[i]) <= 1.0f);
	}
}

void TestLightmap::testTexels()
{
	g_settings->setFloat("lightmap_brightness", 0.5f);
	LightmapLighting params;
	params.enabled = true;

	// No time passes: no flicker
	LightmapState noon;
	noon.step(0.0f, params, 0.5f, 15);
	check_table(noon, expected_day);

	LightmapState midnight;
	midnight.step(0.0f, params, 0.0f, 15);
	check_table(midnight, expected_night);
}

